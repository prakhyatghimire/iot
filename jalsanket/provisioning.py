"""ThingsBoard Cloud desired-state documents and REST provisioning client.

Cloud uses MQTT/TLS on 8883 and HTTPS REST on 443. REST calls need either a
tenant JWT supplied through ``TB_REST_JWT`` (the browser session already
configured this tenant) or explicit admin credentials for a self-hosted login.
Nothing is hard-coded. The client is usable with an injected HTTP function so
payloads can be verified locally; the default transport uses only the standard
library.

Cloud Alarm Rules 2.0 are generated by ``alarm_rules.py`` and the Cloud dashboard
by ``dashboard.py``. The legacy CE rule-chain artifact is retained only for the
local regression suite; Cloud alarm behavior is carried by the six Alarm Rules
2.0 definitions applied to the device profile.
"""

from __future__ import annotations

import json
import logging
import os
import urllib.error
import urllib.request
from dataclasses import dataclass
from typing import Callable, Optional

from .alarm_rules import cloud_alarm_rules
from .config import ConfigurationError, RestConfig, load_dotenv
from .fleet import FleetConfig, NodeConfig

logger = logging.getLogger("jalsanket.provisioning")

DEVICE_PROFILE_NAME = "JalSanket Water Quality Node"
TELEMETRY_KEYS = (
    "ph",
    "turbidity_ntu",
    "tds_ppm",
    "water_temp_c",
    "flow_lpm",
    "latitude",
    "longitude",
)
INACTIVITY_TIMEOUT_MS = 60_000

HttpFunction = Callable[[str, str, Optional[dict], Optional[dict]], tuple[int, dict]]


@dataclass(frozen=True)
class ThingsBoardConfig:
    host: str
    admin_username: str = ""
    admin_password: str = ""
    rest_host: str = ""
    http_scheme: str = "https"
    http_port: int = 443
    rest_jwt: str = ""

    @property
    def base_url(self) -> str:
        return RestConfig(
            host=self.host,
            rest_host=self.rest_host or self.host,
            scheme=self.http_scheme,
            port=self.http_port,
        ).base_url

    @classmethod
    def from_env(cls) -> "ThingsBoardConfig":
        load_dotenv()
        rest = RestConfig.from_env()
        return cls(
            host=rest.host,
            admin_username=os.environ.get("TB_ADMIN_USERNAME", ""),
            admin_password=os.environ.get("TB_ADMIN_PASSWORD", ""),
            rest_host=rest.rest_host,
            http_scheme=rest.scheme,
            http_port=rest.port,
            rest_jwt=os.environ.get("TB_REST_JWT", ""),
        )

    def safe_summary(self) -> dict:
        return {
            "host": self.host,
            "rest_host": self.rest_host or self.host,
            "http_scheme": self.http_scheme,
            "http_port": self.http_port,
            "admin_username": self.admin_username or None,
            "password_present": bool(self.admin_password),
            "rest_jwt_present": bool(self.rest_jwt),
        }


def urllib_http(method: str, url: str, body: Optional[dict] = None,
                headers: Optional[dict] = None) -> tuple[int, dict]:
    """Minimal stdlib HTTP JSON transport used by the provisioning client."""
    data = json.dumps(body).encode("utf-8") if body is not None else None
    request_headers = {"Content-Type": "application/json"}
    if headers:
        request_headers.update(headers)
    request = urllib.request.Request(url, data=data, headers=request_headers, method=method)
    try:
        with urllib.request.urlopen(request, timeout=15) as response:
            raw = response.read().decode("utf-8")
            return response.status, (json.loads(raw) if raw else {})
    except urllib.error.HTTPError as exc:
        raw = exc.read().decode("utf-8")
        return exc.code, (json.loads(raw) if raw else {})


def device_profile_document() -> dict:
    """Desired Cloud device profile with the documented 60 s timeout.

    The top-level ``inactivityTimeout`` is retained as the desired-state value
    asserted by the local regression suite. On ThingsBoard Cloud the effective
    per-device override is the ``inactivityTimeout`` SERVER_SCOPE attribute
    applied by ``ThingsBoardProvisioner.ensure_devices()``.
    """
    return {
        "name": DEVICE_PROFILE_NAME,
        "type": "DEFAULT",
        "inactivityTimeout": INACTIVITY_TIMEOUT_MS,
        "profileData": {
            "configuration": {"type": "DEFAULT"},
            "transportConfiguration": {
                "type": "MQTT",
                "deviceTelemetryTopic": "v1/devices/me/telemetry",
                "deviceAttributesTopic": "v1/devices/me/attributes",
                "deviceAttributesSubscribeTopic": "v1/devices/me/attributes",
                "transportPayloadTypeConfiguration": {
                    "transportPayloadType": "JSON",
                },
            },
            "provisionConfiguration": {
                "type": "DISABLED",
                "provisionDeviceSecret": None,
            },
            "telemetryKeys": list(TELEMETRY_KEYS),
            "alarms": [],
        },
    }


def device_document(node: NodeConfig, profile_id: Optional[str] = None) -> dict:
    return {
        "name": node.device_name,
        "type": DEVICE_PROFILE_NAME,
        "label": f"{node.node_id} - {node.device_name}",
        "profileId": profile_id or "",
        "additionalInfo": {
            "description": "Virtual ESP32-S3 water-quality monitoring node",
            "latitude": node.latitude,
            "longitude": node.longitude,
        },
    }


class ThingsBoardProvisioner:
    """Creates/updates the profile, three devices, tokens and dashboard."""

    def __init__(
        self,
        config: ThingsBoardConfig,
        fleet_config: FleetConfig,
        http: Optional[HttpFunction] = None,
    ) -> None:
        self.config = config
        self.fleet_config = fleet_config
        self._http = http or urllib_http
        self._jwt: Optional[str] = config.rest_jwt or None
        self.profile_id: Optional[str] = None
        self.device_ids: dict[str, str] = {}

    def _request(self, method: str, path: str, body: Optional[dict] = None,
                 authenticated: bool = True) -> dict:
        headers = {}
        if authenticated and self._jwt:
            headers["X-Authorization"] = f"Bearer {self._jwt}"
        status, payload = self._http(method, self.config.base_url + path, body, headers)
        if status >= 400:
            raise RuntimeError(f"ThingsBoard {method} {path} failed with HTTP {status}: {payload}")
        return payload

    def login(self) -> None:
        if self._jwt:
            logger.info("Using configured REST token host=%s", self.config.host)
            return
        if not self.config.admin_username or not self.config.admin_password:
            raise ConfigurationError(
                "Supply TB_REST_JWT for Cloud REST access, or TB_ADMIN_USERNAME "
                "and TB_ADMIN_PASSWORD for a self-hosted login"
            )
        payload = self._request(
            "POST",
            "/api/auth/login",
            {"username": self.config.admin_username, "password": self.config.admin_password},
            authenticated=False,
        )
        self._jwt = payload.get("token")
        if not self._jwt:
            raise RuntimeError("ThingsBoard login response did not contain a token")
        logger.info("ThingsBoard authenticated host=%s", self.config.host)

    def ensure_device_profile(self) -> dict:
        existing = self._request("GET", "/api/deviceProfiles?pageSize=100&page=0")
        desired = device_profile_document()
        for profile in existing.get("data", []):
            if profile.get("name") == DEVICE_PROFILE_NAME:
                self.profile_id = profile.get("id", {}).get("id")
                logger.info("Device profile already exists id=%s", self.profile_id)
                return profile
        created = self._request("POST", "/api/deviceProfile", desired)
        self.profile_id = created.get("id", {}).get("id")
        logger.info("Device profile created id=%s inactivity_timeout_ms=%d",
                    self.profile_id, INACTIVITY_TIMEOUT_MS)
        return created

    def ensure_devices(self) -> list[dict]:
        if self.profile_id is None:
            self.ensure_device_profile()
        results = []
        for node in self.fleet_config.nodes:
            desired = device_document(node, self.profile_id)
            listing = self._request("GET", "/api/tenant/devices?pageSize=100&page=0")
            device = next(
                (d for d in listing.get("data", []) if d.get("name") == node.device_name),
                None,
            )
            if device is None:
                device = self._request("POST", "/api/device", desired)
            device_id = device.get("id", {}).get("id")
            self.device_ids[node.node_id] = device_id
            access_token = node.resolve_token()
            credentials = {
                "id": {"entityType": "DEVICE_CREDENTIAL", "id": device_id},
                "deviceId": {"entityType": "DEVICE", "id": device_id},
                "credentialsType": "ACCESS_TOKEN",
                "credentialsId": access_token,
                "accessToken": access_token,
            }
            self._request("POST", "/api/device/credentials", credentials)
            self._request(
                "POST",
                f"/api/plugins/telemetry/DEVICE/{device_id}/SERVER_SCOPE",
                {"inactivityTimeout": INACTIVITY_TIMEOUT_MS},
            )
            logger.info(
                "Device configured node=%s name=%s id=%s coordinates=(%.4f, %.4f)",
                node.node_id, node.device_name, device_id, node.latitude, node.longitude,
            )
            results.append(device)
        return results

    def ensure_alarm_rules(self) -> list[dict]:
        """Create or update the six Cloud Alarm Rules 2.0 definitions."""
        if self.profile_id is None:
            self.ensure_device_profile()
        existing = self._request(
            "GET",
            f"/api/alarm/rules?entityType=DEVICE_PROFILE&entityId={self.profile_id}"
            "&pageSize=100&page=0",
        )
        by_name = {rule.get("name"): rule for rule in existing.get("data", [])}
        applied: list[dict] = []
        for desired in cloud_alarm_rules(self.profile_id):
            current = by_name.get(desired["name"])
            if current and current.get("id", {}).get("id"):
                desired["id"] = current["id"]
            saved = self._request("POST", "/api/alarm/rule", desired)
            applied.append(saved)
            logger.info("Alarm rule applied name=%s", desired["name"])
        return applied

    def import_dashboard(self, dashboard: dict) -> dict:
        result = self._request("POST", "/api/dashboard", dashboard)
        logger.info("Dashboard imported title=%s", dashboard.get("title"))
        return result

    def provisioning_summary(self) -> dict:
        return {
            **self.config.safe_summary(),
            "deviceProfile": DEVICE_PROFILE_NAME,
            "devices": [n.device_name for n in self.fleet_config.nodes],
            "telemetryKeys": list(TELEMETRY_KEYS),
            "inactivityTimeoutMs": INACTIVITY_TIMEOUT_MS,
            "deviceIds": self.device_ids,
        }
