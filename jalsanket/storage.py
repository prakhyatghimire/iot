"""SQLite store-and-forward buffer (Phase 2).

SQLite is the local source of truth. Every reading generated by the virtual
node is inserted here *before* any transport is attempted. Transport code
added in later phases must only consume rows returned by
``get_unsynced_batch()`` and may only call ``mark_synced()`` after a confirmed
QoS 1 delivery.

Time semantics (deliberately kept separate):

* ``acquisition_ms`` comes from the reading's acquisition timestamp. In live
  operation this is real wall-clock UTC. It is the timestamp that must be
  preserved when buffered rows are replayed later.
* ``stored_at_ms`` and ``synced_at_ms`` are recorded with ``time.time()`` at
  the moment of the local database operation. They are the real-clock anchors
  used for latency and recovery measurements.
* The generator's simulated/scenario clock is intentionally NOT stored here,
  so it can never be confused with measurement time.
"""

from __future__ import annotations

import logging
import sqlite3
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Optional

from .telemetry import Reading

logger = logging.getLogger("jalsanket.storage")

SCHEMA = """
CREATE TABLE IF NOT EXISTS readings (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    node_id         TEXT    NOT NULL,
    acquisition_ms  INTEGER NOT NULL,
    acquired_at     TEXT    NOT NULL,
    ph              REAL    NOT NULL,
    turbidity_ntu   REAL    NOT NULL,
    tds_ppm         REAL    NOT NULL,
    water_temp_c    REAL    NOT NULL,
    flow_lpm        REAL    NOT NULL,
    latitude        REAL    NOT NULL,
    longitude       REAL    NOT NULL,
    synced          INTEGER NOT NULL DEFAULT 0 CHECK (synced IN (0, 1)),
    stored_at_ms    INTEGER NOT NULL,
    synced_at_ms    INTEGER,
    publish_attempts INTEGER NOT NULL DEFAULT 0,
    last_error      TEXT
);

CREATE INDEX IF NOT EXISTS idx_readings_unsynced_order
    ON readings (synced, acquisition_ms, id);

CREATE INDEX IF NOT EXISTS idx_readings_node_unsynced_order
    ON readings (node_id, synced, acquisition_ms, id);

CREATE TABLE IF NOT EXISTS loss_events (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    occurred_at_ms  INTEGER NOT NULL,
    node_id         TEXT    NOT NULL,
    reason          TEXT    NOT NULL,
    acquisition_ms  INTEGER NOT NULL,
    detail          TEXT
);
"""


@dataclass(frozen=True)
class StoreConfig:
    """Configuration of the durable buffer."""

    db_path: str = "data/jalsanket.db"
    max_buffer_rows: int = 10_800  # 6 hours at the default 2 s sample interval
    eviction_policy: str = "drop_newest"
    synchronous: str = "FULL"  # strongest WAL durability; fsync per commit

    def __post_init__(self) -> None:
        if self.max_buffer_rows <= 0:
            raise ValueError("max_buffer_rows must be positive")
        if self.eviction_policy != "drop_newest":
            raise ValueError(
                "only 'drop_newest' is implemented; it is the policy that does "
                "not delete already-buffered unsynchronized readings"
            )
        if self.synchronous not in {"FULL", "NORMAL", "OFF"}:
            raise ValueError("synchronous must be FULL, NORMAL or OFF")


@dataclass(frozen=True)
class InsertOutcome:
    """Result of persisting one reading."""

    inserted: bool
    row_id: Optional[int]
    buffer_depth: int
    capacity: int
    loss_event_id: Optional[int] = None


@dataclass(frozen=True)
class StoredReading:
    """A row retrieved from the buffer, ready for later transport."""

    id: int
    node_id: str
    acquisition_ms: int
    acquired_at: str
    ph: float
    turbidity_ntu: float
    tds_ppm: float
    water_temp_c: float
    flow_lpm: float
    latitude: float
    longitude: float
    stored_at_ms: int
    synced_at_ms: Optional[int]
    publish_attempts: int
    last_error: Optional[str]

    def values(self) -> dict[str, float]:
        """Telemetry fields only (no timestamps or sync metadata)."""
        return {
            "ph": self.ph,
            "turbidity_ntu": self.turbidity_ntu,
            "tds_ppm": self.tds_ppm,
            "water_temp_c": self.water_temp_c,
            "flow_lpm": self.flow_lpm,
            "latitude": self.latitude,
            "longitude": self.longitude,
        }

    @classmethod
    def from_row(cls, row: sqlite3.Row) -> "StoredReading":
        return cls(
            id=row["id"],
            node_id=row["node_id"],
            acquisition_ms=row["acquisition_ms"],
            acquired_at=row["acquired_at"],
            ph=row["ph"],
            turbidity_ntu=row["turbidity_ntu"],
            tds_ppm=row["tds_ppm"],
            water_temp_c=row["water_temp_c"],
            flow_lpm=row["flow_lpm"],
            latitude=row["latitude"],
            longitude=row["longitude"],
            stored_at_ms=row["stored_at_ms"],
            synced_at_ms=row["synced_at_ms"],
            publish_attempts=row["publish_attempts"],
            last_error=row["last_error"],
        )


class TelemetryStore:
    """Durable SQLite buffer with explicit capacity and drop-newest eviction."""

    def __init__(self, config: Optional[StoreConfig] = None) -> None:
        self.config = config or StoreConfig()
        db_path = Path(self.config.db_path)
        db_path.parent.mkdir(parents=True, exist_ok=True)

        self._conn = sqlite3.connect(db_path, isolation_level=None, timeout=30.0)
        self._conn.row_factory = sqlite3.Row
        self._conn.execute("PRAGMA journal_mode=WAL")
        self._conn.execute(f"PRAGMA synchronous={self.config.synchronous}")
        self._conn.execute("PRAGMA busy_timeout=30000")
        self._conn.executescript(SCHEMA)

        logger.info(
            "store opened path=%s journal_mode=WAL capacity=%d policy=%s unsynced=%d",
            db_path,
            self.config.max_buffer_rows,
            self.config.eviction_policy,
            self.get_buffer_depth(),
        )

    def close(self) -> None:
        self._conn.close()

    def __enter__(self) -> "TelemetryStore":
        return self

    def __exit__(self, exc_type, exc, tb) -> None:
        self.close()

    # --------------------------------------------------------------- metrics
    def journal_mode(self) -> str:
        return str(self._conn.execute("PRAGMA journal_mode").fetchone()[0])

    def get_buffer_depth(self, node_id: Optional[str] = None) -> int:
        """Number of unsynchronized rows currently awaiting transport."""
        if node_id is None:
            row = self._conn.execute("SELECT COUNT(*) AS n FROM readings WHERE synced = 0").fetchone()
        else:
            row = self._conn.execute(
                "SELECT COUNT(*) AS n FROM readings WHERE synced = 0 AND node_id = ?",
                (node_id,),
            ).fetchone()
        return int(row["n"])

    def total_rows(self) -> int:
        return int(self._conn.execute("SELECT COUNT(*) AS n FROM readings").fetchone()["n"])

    def data_loss_count(self) -> int:
        return int(self._conn.execute("SELECT COUNT(*) AS n FROM loss_events").fetchone()["n"])

    # ------------------------------------------------------------- persistence
    def persist(self, reading: Reading) -> InsertOutcome:
        """Write one reading to SQLite. This must happen before any publish.

        When the unsynchronized buffer is full, drop-newest rejects the new
        reading and records a durable loss event. Already-buffered rows are
        never deleted.
        """
        now_ms = int(time.time() * 1000)
        self._conn.execute("BEGIN IMMEDIATE")
        try:
            depth = self.get_buffer_depth(reading.node_id)
            capacity = self.config.max_buffer_rows

            if depth >= capacity:
                cursor = self._conn.execute(
                    "INSERT INTO loss_events "
                    "(occurred_at_ms, node_id, reason, acquisition_ms, detail) "
                    "VALUES (?, ?, ?, ?, ?)",
                    (
                        now_ms,
                        reading.node_id,
                        "buffer_full_drop_newest",
                        reading.acquisition_ms(),
                        f"buffer_depth={depth} capacity={capacity}",
                    ),
                )
                loss_id = int(cursor.lastrowid)
                self._conn.execute("COMMIT")
                logger.warning(
                    "BUFFER FULL - DROPPING NEWEST node=%s acquisition_ms=%d "
                    "buffer_depth=%d capacity=%d data_loss_count=%d",
                    reading.node_id,
                    reading.acquisition_ms(),
                    depth,
                    capacity,
                    self.data_loss_count(),
                )
                return InsertOutcome(
                    inserted=False,
                    row_id=None,
                    buffer_depth=depth,
                    capacity=capacity,
                    loss_event_id=loss_id,
                )

            cursor = self._conn.execute(
                "INSERT INTO readings "
                "(node_id, acquisition_ms, acquired_at, ph, turbidity_ntu, tds_ppm, "
                " water_temp_c, flow_lpm, latitude, longitude, stored_at_ms) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                (
                    reading.node_id,
                    reading.acquisition_ms(),
                    reading.acquired_at.isoformat(),
                    reading.ph,
                    reading.turbidity_ntu,
                    reading.tds_ppm,
                    reading.water_temp_c,
                    reading.flow_lpm,
                    reading.latitude,
                    reading.longitude,
                    now_ms,
                ),
            )
            row_id = int(cursor.lastrowid)
            self._conn.execute("COMMIT")
            new_depth = self.get_buffer_depth(reading.node_id)
            logger.info(
                "STORED node=%s id=%d acquisition_ms=%d stored_at_ms=%d "
                "buffer_depth=%d capacity=%d",
                reading.node_id,
                row_id,
                reading.acquisition_ms(),
                now_ms,
                new_depth,
                capacity,
            )
            return InsertOutcome(
                inserted=True,
                row_id=row_id,
                buffer_depth=new_depth,
                capacity=capacity,
            )
        except Exception:
            self._conn.execute("ROLLBACK")
            raise

    # --------------------------------------------------------------- retrieval
    def get_unsynced_batch(
        self, limit: int, node_id: Optional[str] = None
    ) -> list[StoredReading]:
        """Return the oldest unsynchronized rows in chronological order.

        Ordering uses the original acquisition timestamp, with ``id`` as a
        deterministic tie-breaker. Replay later must use this same order.
        """
        if limit <= 0:
            raise ValueError("limit must be positive")
        if node_id is None:
            rows = self._conn.execute(
                "SELECT * FROM readings WHERE synced = 0 "
                "ORDER BY acquisition_ms ASC, id ASC LIMIT ?",
                (limit,),
            ).fetchall()
        else:
            rows = self._conn.execute(
                "SELECT * FROM readings WHERE synced = 0 AND node_id = ? "
                "ORDER BY acquisition_ms ASC, id ASC LIMIT ?",
                (node_id, limit),
            ).fetchall()
        return [StoredReading.from_row(row) for row in rows]

    # ------------------------------------------------------------------ sync
    def mark_synced(self, row_ids: Iterable[int]) -> int:
        """Mark rows synchronized. Call only after confirmed delivery.

        Returns the number of rows that actually changed state.
        """
        ids = list(row_ids)
        if not ids:
            return 0
        now_ms = int(time.time() * 1000)
        self._conn.execute("BEGIN IMMEDIATE")
        try:
            cursor = self._conn.executemany(
                "UPDATE readings SET synced = 1, synced_at_ms = ? "
                "WHERE id = ? AND synced = 0",
                [(now_ms, row_id) for row_id in ids],
            )
            changed = int(cursor.rowcount)
            self._conn.execute("COMMIT")
        except Exception:
            self._conn.execute("ROLLBACK")
            raise
        remaining = self.get_buffer_depth()
        logger.info(
            "SYNCED rows_flushed=%d remaining_rows=%d buffer_depth=%d capacity=%d",
            changed,
            remaining,
            remaining,
            self.config.max_buffer_rows,
        )
        return changed

    def record_publish_attempt(self, row_ids: Iterable[int], error: Optional[str] = None) -> None:
        """Record retry information for rows whose publish attempt failed."""
        ids = list(row_ids)
        if not ids:
            return
        self._conn.execute("BEGIN IMMEDIATE")
        try:
            self._conn.executemany(
                "UPDATE readings SET publish_attempts = publish_attempts + 1, "
                "last_error = ? WHERE id = ? AND synced = 0",
                [(error, row_id) for row_id in ids],
            )
            self._conn.execute("COMMIT")
        except Exception:
            self._conn.execute("ROLLBACK")
            raise
